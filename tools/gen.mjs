#!/usr/bin/env node
// networks.json  ->  generated copies (never edit these by hand):
//   js/src/networks.generated.ts          typed TS module compiled into dist/ (no runtime JSON reads)
//   go/bridgesdk/networks.json            byte-identical copy, //go:embed'ed by package bridgesdk
//   cast/env.mainnet.sh, cast/env.testnet.sh
//   GUIDE.md                              the blocks between <!-- BEGIN:networks --> / <!-- END:networks -->
// Usage: node tools/gen.mjs          (writes)      node tools/gen.mjs --check   (exit 1 if a copy is stale)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const kit = resolve(here, '..');
const check = process.argv.includes('--check');
const raw = readFileSync(resolve(kit, 'networks.json'), 'utf8');
const data = JSON.parse(raw);

const outputs = new Map(); // relative path -> content

// ---- JS ------------------------------------------------------------------------------------------------------------
outputs.set(
  'js/src/networks.generated.ts',
  `// GENERATED by tools/gen.mjs from networks.json - DO NOT EDIT.\nimport type { NetworksData } from './networks-types.js';\n\nexport const networksData: NetworksData = ${JSON.stringify(data, null, 2)};\n`,
);

// ---- Go ------------------------------------------------------------------------------------------------------------
outputs.set('go/bridgesdk/networks.json', raw);

// ---- cast env -----------------------------------------------------------------------------------------------------
const CH = { one: 'ONE', bsc: 'BSC', hyperevm: 'HYPEREVM' };
const tokenVar = { one: { ONE: null, USDTx: 'USDTX', ONEUSD: 'ONEUSD', WCROSS: 'WCROSS' }, bsc: { ONE: 'ONE_TOKEN', USDT: 'USDT' }, hyperevm: { ONE: 'ONE_TOKEN' } };

function envFile(netKey) {
  const net = data.networks[netKey];
  const lines = [];
  const add = (name, value, todo) => {
    lines.push(`export ${name}=${value == null ? '""' : JSON.stringify(String(value))}`);
    if (value == null) lines.push(`export TODO_${name}=${JSON.stringify(todo || 'TODO(UNCONFIRMED)')}`);
  };
  lines.push('#!/usr/bin/env bash', '# GENERATED by tools/gen.mjs from networks.json - DO NOT EDIT.', `# Source this file:  source cast/env.${netKey}.sh`, `export NETWORK=${JSON.stringify(netKey)}`, `export VERIFIED_AT=${JSON.stringify(data.verifiedAt)}`, 'export NATIVE=0x0000000000000000000000000000000000000001');
  for (const [ck, c] of Object.entries(net.chains)) {
    const P = CH[ck];
    lines.push('', `# ---- ${c.name}`);
    add(`${P}_CHAIN_ID`, c.chainId);
    add(`${P}_RPC`, c.rpc);
    add(`${P}_EXPLORER`, c.explorer, c.todo?.explorer);
    add(`${P}_NATIVE_SYMBOL`, c.nativeSymbol, c.todo?.nativeSymbol);
    add(`${P}_BRIDGE`, c.bridge, c.todo?.bridge);
    add(`${P}_VERIFIER_INFO`, c.bridgeVerifier, c.todo?.bridgeVerifier);
    add(`${P}_EXECUTOR_INFO`, c.bridgeExecutor, c.todo?.bridgeExecutor);
    for (const [tk, t] of Object.entries(c.tokens || {})) {
      const v = tokenVar[ck]?.[tk];
      if (v === null) continue; // native sentinel is $NATIVE
      if (!v) throw new Error(`gen.mjs: no env name for token ${ck}.${tk}`);
      add(`${P}_${v}`, t ? t.address : null, c.todo?.[`tokens.${tk}`]);
    }
    if (ck === 'hyperevm') {
      add('HYPEREVM_CORE_SYSTEM', c.coreSystemAddress, c.todo?.coreSystemAddress);
      add('HYPEREVM_CORE_INFO_API', c.coreInfoApi, c.todo?.coreInfoApi);
    }
    if (c.swap) {
      add(`${P}_V3_ROUTER`, c.swap.v3SwapRouter, c.todo?.['swap.v3SwapRouter']);
      add(`${P}_QUOTER_V2`, c.swap.quoterV2, c.todo?.['swap.quoterV2']);
      add(`${P}_V3_FACTORY`, c.swap.v3Factory, c.todo?.['swap.v3Factory']);
      add(`${P}_SWAP_BRIDGE_ROUTER`, c.swap.swapBridgeRouter, c.todo?.['swap.swapBridgeRouter']);
      add(`${P}_X1_POOL`, c.swap.x1Pool ? c.swap.x1Pool.pool : null, c.todo?.['swap.x1Pool']);
      add(`${P}_X1_POOL_FEE`, c.swap.x1Pool ? c.swap.x1Pool.fee : null, c.todo?.['swap.x1Pool']);
    }
  }
  return lines.join('\n') + '\n';
}
outputs.set('cast/env.mainnet.sh', envFile('mainnet'));
outputs.set('cast/env.testnet.sh', envFile('testnet'));

// ---- GUIDE.md network tables ------------------------------------------------------------------------------------------
function guideTables() {
  const md = [];
  const cell = (v, todo) => (v == null ? `⚠️ \`null\` — ${todo || 'TODO(UNCONFIRMED)'}` : `\`${v}\``);
  for (const [netKey, net] of Object.entries(data.networks)) {
    md.push(`### ${net.label}`, '');
    md.push('| 체인 | chainId | RPC (공개) | Explorer | 네이티브 |', '|---|---|---|---|---|');
    for (const [, c] of Object.entries(net.chains)) {
      md.push(`| ${c.name} | \`${c.chainId}\` | \`${c.rpc}\` | ${cell(c.explorer, c.todo?.explorer)} | ${c.nativeSymbol ? '`' + c.nativeSymbol + '`' : '⚠️ ' + (c.todo?.nativeSymbol || 'TODO(UNCONFIRMED)')} |`);
    }
    md.push('', '| 체인 | 역할 | 주소 |', '|---|---|---|');
    for (const [ck, c] of Object.entries(net.chains)) {
      md.push(`| ${CH[ck]} | 브리지 (프록시) — 직접 호출 | ${cell(c.bridge, c.todo?.bridge)} |`);
      for (const [tk, t] of Object.entries(c.tokens || {})) {
        const label = t && t.kind === 'native' ? `네이티브 토큰 센티넬 (ONE)` : `토큰 ${tk}${t && t.symbol ? ` (${t.symbol}, ${t.decimals} dec)` : ''}${t && t.status ? ` [${t.status}]` : ''}`;
        md.push(`| ${CH[ck]} | ${label} | ${cell(t ? t.address : null, c.todo?.[`tokens.${tk}`])} |`);
      }
      if (c.swap) {
        md.push(`| ${CH[ck]} | Uniswap V3 SwapRouter (X1 extraCall 타깃) | ${cell(c.swap.v3SwapRouter)} |`);
        md.push(`| ${CH[ck]} | QuoterV2 | ${cell(c.swap.quoterV2)} |`);
        md.push(`| ${CH[ck]} | SwapBridgeRouter (X3) | ${cell(c.swap.swapBridgeRouter, c.todo?.['swap.swapBridgeRouter'])} |`);
        md.push(`| ${CH[ck]} | USDTx/ONEUSD 풀 (fee 0) | ${cell(c.swap.x1Pool ? c.swap.x1Pool.pool : null, c.todo?.['swap.x1Pool'])} |`);
      }
      if (ck === 'hyperevm') md.push(`| ${CH[ck]} | HyperCore 시스템 주소 (ONE) | ${cell(c.coreSystemAddress, c.todo?.coreSystemAddress)} |`);
      md.push(`| ${CH[ck]} | (참고) BridgeVerifier — SDK 는 라이브 조회 | ${cell(c.bridgeVerifier, c.todo?.bridgeVerifier)} |`);
      md.push(`| ${CH[ck]} | (참고) BridgeExecutor — SDK 는 라이브 조회 | ${c.bridgeExecutor ? '`' + c.bridgeExecutor + '`' : ck === 'bsc' ? '— (리프 체인, 없음)' : cell(null, c.todo?.bridgeExecutor)} |`);
    }
    md.push('');
  }
  return md.join('\n');
}
const guidePath = resolve(kit, 'GUIDE.md');
const BEGIN = '<!-- BEGIN:networks (generated by tools/gen.mjs from networks.json - do not edit) -->';
const END = '<!-- END:networks -->';
if (existsSync(guidePath)) {
  const g = readFileSync(guidePath, 'utf8');
  const i = g.indexOf('<!-- BEGIN:networks'), j = g.indexOf(END);
  if (i >= 0 && j > i) outputs.set('GUIDE.md', g.slice(0, i) + BEGIN + '\n\n' + guideTables() + '\n' + g.slice(j));
}

// ---- write / check -------------------------------------------------------------------------------------------------
let stale = 0;
for (const [rel, content] of outputs) {
  const p = resolve(kit, rel);
  const cur = existsSync(p) ? readFileSync(p, 'utf8') : null;
  if (cur === content) continue;
  if (check) {
    console.error(`STALE ${rel}`);
    stale++;
  } else {
    writeFileSync(p, content);
    console.log(`wrote ${rel}`);
  }
}
if (check && stale) process.exit(1);
if (!stale) console.log(check ? 'all generated copies are current' : 'done');
